-- ==========================================

-- 1. Порівняння (оператори =, >, <, <>)
-- Отримуємо всі послуги, базова ціна яких строго більша за 60 грн
SELECT * FROM ServiceTypes
WHERE BasePrice > 60.00;
GO

-- Шукаємо клієнтів, які є 'VIP' (використовуємо N для кирилиці)
SELECT * FROM Clients
WHERE ClientType = N'VIP';
GO

-- 2. Фільтрація за шаблоном (LIKE)
-- Символ '%' означає будь-яку кількість будь-яких символів до або після слова
-- Знайдемо відділення, в адресі яких є слово "Політехнічна"
SELECT * FROM Branches
WHERE Address LIKE N'%Політехнічна%';
GO

-- Знайдемо клієнтів, чий номер телефону починається на '+38067'
SELECT * FROM Clients
WHERE Phone LIKE '+38067%';
GO

-- 3. Фільтрація за діапазоном (BETWEEN)
-- Отримуємо послуги, базова ціна яких знаходиться в межах від 40 до 120 грн (включно)
SELECT * FROM ServiceTypes
WHERE BasePrice BETWEEN 40.00 AND 120.00;
GO